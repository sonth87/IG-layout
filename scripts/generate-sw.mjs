// Generates out/sw.js after `next build` (static export). The service worker
// precaches every exported file so the app works offline (M1, D-42).
// Cache name = hash of all file contents, so each deploy gets a fresh cache.

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.resolve("out");
const SKIP = new Set(["sw.js"]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])),
  );
  return files.flat();
}

function toUrl(file) {
  const rel = path.relative(OUT, file).split(path.sep).join("/");
  if (rel === "index.html") return "/";
  if (rel.endsWith("/index.html")) return `/${rel.slice(0, -"index.html".length)}`;
  return `/${rel}`;
}

const files = (await walk(OUT)).filter((f) => !SKIP.has(path.basename(f))).sort();
const hash = createHash("sha256");
for (const f of files) hash.update(f).update(await readFile(f));
const version = hash.digest("hex").slice(0, 12);
const urls = files.map(toUrl);

const sw = `// Generated by scripts/generate-sw.mjs — do not edit.
const CACHE = "ig-layout-${version}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

function putInCache(request, response) {
  if (response.ok) {
    const copy = response.clone();
    caches.open(CACHE).then((cache) => cache.put(request, copy));
  }
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;

  // Pages: network first (fresh deploys), cache when offline.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => putInCache(request, response))
        .catch(() => caches.match(request).then((hit) => hit || caches.match("/"))),
    );
    return;
  }

  // Assets: cache first (file names are content-hashed).
  event.respondWith(
    caches.match(request).then((hit) => hit || fetch(request).then((response) => putInCache(request, response))),
  );
});
`;

await writeFile(path.join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached, cache ig-layout-${version}`);
