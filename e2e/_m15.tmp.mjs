import { chromium } from "playwright-core";
import { chromePath, skipTips } from "./lib.mjs";
const S = process.argv[3];
const b = await chromium.launch({ executablePath: chromePath() });
const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: "dark" });
await skipTips(c);
const p = await c.newPage();
p.on("pageerror", (e) => console.log("ERR", e));
await p.goto(process.argv[2]);
await p.getByRole("button", { name: "New project" }).click();
await p.locator("input[type=file]").setInputFiles(["e2e/fixtures/p3.jpg", "e2e/fixtures/p4.jpg", "e2e/fixtures/portrait.jpg"]);
await p.getByRole("button", { name: "Skip" }).click();
await p.waitForTimeout(1200);
await p.evaluate(() => window.__igEditor.getState().select(null));
await p.waitForTimeout(400);
await p.screenshot({ path: `${S}/m15-1.png` });
await p.getByRole("button", { name: "Slide 2 options" }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${S}/m15-2.png` });
await p.mouse.click(10, 300);
await p.getByRole("button", { name: "Add slide" }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${S}/m15-3.png` });
await p.getByRole("button", { name: "Grid 9", exact: true }).click();
await p.waitForTimeout(600);
await p.screenshot({ path: `${S}/m15-4.png` });
await b.close();
